#!/bin/bash

# Проверяем, передан ли первый и единственный аргумент
[ -z "$1" ] && { echo "Использование: $0 <каталог>" >&2; exit 1; }

# Проверяем, существует ли указанная в аргументе директория
[ ! -d "$1" ] && { echo "Ошибка: '$1' — не каталог" >&2; exit 1; }

# Формируем имя файла на основе текущей даты и времени
NOW=$(date +%Y%m%d_%H%M%S)
OUT="/tmp/backup_$NOW.tar.gz"

# Используем временное расширение, чтобы другие процессы не прочитали неполный архив
PART="$OUT.part"

# Удаляем временный файл, если пользователь прервет скрипт (Ctrl+C)
trap 'rm -f "$PART"; exit 1' SIGINT

# Создаем архив, скрывая стандартные предупреждения tar
if tar -czf "$PART" "$1" 2>/dev/null; then
    # Переименовываем готовый архив в финальное имя
    mv "$PART" "$OUT"   
    echo "Готово: $OUT"
else
    echo "Ошибка архивации" >&2
    # Удаляем поврежденный временный файл в случае сбоя команды tar
    rm -f "$PART"       
    exit 1
fi
